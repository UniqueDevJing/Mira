from reportlab.pdfbase.ttfonts import TTFont
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer

pdfmetrics.registerFont(TTFont("CN", "C:/Windows/Fonts/msyh.ttc"))
pdfmetrics.registerFont(TTFont("CNB", "C:/Windows/Fonts/msyhbd.ttc"))

OUT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__))) + "/tests/fixtures"

styles = getSampleStyleSheet()
for name, font, size, leading, color, sa, sb in [
    ("CNTitle", "CNB", 18, 26, "#1a1a2e", 12, 20),
    ("CNH1", "CNB", 14, 22, "#0f3460", 10, 16),
    ("CNH2", "CNB", 12, 18, "#2d3436", 8, 12),
    ("CNBody", "CN", 10, 16, "#2d3436", 6, 0),
]:
    styles.add(
        ParagraphStyle(
            name, fontName=font, fontSize=size, leading=leading, textColor=color, spaceAfter=sa, spaceBefore=sb
        )
    )


def H1(t):
    return Paragraph(t, styles["CNH1"])


def H2(t):
    return Paragraph(t, styles["CNH2"])


def P(t):
    return Paragraph(t, styles["CNBody"])


def SP(v=4):
    return Spacer(1, v * mm)


def make_doc(filename, title, blocks):
    doc = SimpleDocTemplate(
        f"{OUT_DIR}/{filename}",
        pagesize=A4,
        leftMargin=25 * mm,
        rightMargin=25 * mm,
        topMargin=20 * mm,
        bottomMargin=20 * mm,
    )
    story = [Paragraph(title, styles["CNTitle"]), SP(6)]
    for b in blocks:
        story.append(b)
        story.append(SP(2))
    doc.build(story)
    print(f"Generated: {filename}")


