def main():
    only = None
    for a in sys.argv[1:]:
        if a.startswith("--only="):
            only = [x.strip() for x in a.split("=", 1)[1].split(",")]

    from api.config import settings
    from api.core.document_store import get_document_store
    from api.state import get_bm25_index, get_embedder, get_vector_store
    from engines.chunking.strategies import get_chunker
    from engines.doc_types import get_doc_type
    from engines.parsing.txt_parser import TxtParser

    embedder = get_embedder()
    state_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), ".kb_seed_hash_state.json")
    state = {}
    if os.path.exists(state_path):
        try:
            with open(state_path, encoding="utf-8") as f:
                state = json.load(f)
        except Exception:  # noqa: BLE001 — 状态文件损坏则当空状态重新入库
            state = {}

    uploaded = []
    for kb, docs in ALL_SEEDS.items():
        if only and kb not in only:
            continue
        for doc_data in docs:
            title = doc_data["title"]
            content = doc_data["content"]
            key = f"{kb}:{title}"
            content_hash = hashlib.sha256(content.encode("utf-8")).hexdigest()
            if state.get(key) == content_hash:
                print(f"  [{kb}] SKIP (unchanged): {title}")
                continue

            doc_id = hashlib.sha256(key.encode("utf-8")).hexdigest()[:12]
            spec = get_doc_type(doc_data["doc_type"])
            chunker = get_chunker(spec, settings)
            # NamedTemporaryFile 生命周期与 TxtParser.parse 的路径读取解耦, 非 with 语义
            tmp = tempfile.NamedTemporaryFile("w", suffix=".txt", delete=False, encoding="utf-8")  # noqa: SIM115
            tmp.write(content)
            tmp.close()
            try:
                uir = TxtParser().parse(tmp.name)
            finally:
                os.unlink(tmp.name)
            uir.source["path"] = title + ".txt"
            uir.update_time = int(time.time())
            chunks = chunker.chunk(uir)
            for c in chunks:
                c.doc_id = doc_id

            if not chunks:
                print(f"  [{kb}] SKIPPED (no chunks): {title}")
                continue

            texts = [c.content for c in chunks]
            embeddings = embedder.embed_batch(texts)
            for chunk, emb in zip(chunks, embeddings):
                chunk.embedding = emb

            store = get_vector_store(kb)
            store.insert(chunks)

            bm25_docs = [
                {"id": c.chunk_id, "chunk_id": c.chunk_id, "doc_id": c.doc_id, "content": c.content}
                for c in chunks
            ]
            get_bm25_index(kb).remove_doc(doc_id)
            get_bm25_index(kb).add_documents(bm25_docs)

            # 同步登记进文档库 (documents.db), 保证管理端文档列表与向量库一致
            get_document_store().save(
                doc_id=doc_id,
                filename=title + ".txt",
                status="ready",
                chunk_count=len(chunks),
                knowledge_base=kb,
                doc_type=doc_data["doc_type"],
            )

            state[key] = content_hash
            uploaded.append({"id": doc_id, "title": title, "kb": kb, "chunks": len(chunks)})
            print(f"  [{kb}] {title} -> {len(chunks)} chunks")

    try:
        with open(state_path, "w", encoding="utf-8") as f:
            json.dump(state, f, ensure_ascii=False, indent=2)
    except Exception as e:  # noqa: BLE001
        print(f"  [warn] 哈希状态写入失败(不影响本次): {e}")

    print(f"\nDone: {len(uploaded)} docs, {sum(i['chunks'] for i in uploaded)} chunks")


